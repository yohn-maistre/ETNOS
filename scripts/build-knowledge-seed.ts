// Build the first slice of the knowledge model (research/epistemic-multiplex-2026-11-19.md §4, §8, §15)
// from files already in the repository, without any network or model:
//
// - Witnesses: the seed's sources, with only the quotes that verify-wiki-seed.py confirmed word for word.
// - Entities: catalogue contexts (regions, regencies, cities, languages) and the seed wiki pages
//   (peoples, landscape features, regions), with plain aliases. Topics stay a scheme, not entities.
// - Mentions: exact, longest-first matches of entity names in each confirmed quote. A bare name that
//   could mean more than one entity is not counted.
// - Assertions: (1) region and province membership from the catalogue, accepted with the catalogue
//   entry's own description as the excerpt; (2) proposals from fixed cue phrases between two mentions in
//   one quote, left for a steward to review. Nothing here is generated by a language model.
//
// Usage: node scripts/build-knowledge-seed.ts [output]  (default src/catalogues/tanah-papua-knowledge-seed.json)
import {readFileSync,writeFileSync} from 'node:fs'
import {createHash} from 'node:crypto'

type Quote={section:string;text:string}
type Source={title:string;url:string;publisher?:string;year?:number;language?:string;licence?:string;quotes:Quote[]}
type Entry={slug:string;title:string;kind:string;facet?:string;aliases:string[];parents:string[];description:string}
const root=new URL('..',import.meta.url).pathname
const read=(p:string)=>JSON.parse(readFileSync(root+p,'utf8'))
const regions=['meepago','saireri','la-pago']
const catalogue=read('src/catalogues/tanah-papua.json') as {name:string;version:string;entries:Entry[];sources:{title:string;url:string;used?:string}[]}
const labels=read('src/catalogues/tanah-papua-seed-labels.json') as {pages:{title:string;contexts:string[]}[]}
const digest=(...parts:string[])=>createHash('sha256').update(parts.join('\n')).digest('hex').slice(0,32)
const slugify=(t:string)=>t.toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g,'').replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'')

// ---------- witnesses ----------
type Witness={key:string;kind:'document';title:string;url:string;publisher:string;licence:string|null;year:number|null;language:string|null;voice:string;excerpts:{digest:string;text:string;section:string}[]}
const voiceOf=(url:string)=>/wikipedia\.org/.test(url)?'ensiklopedia':/\.go\.id|bappenas|kemendagri|bps\./.test(url)?'pemerintah':'lainnya'
// The verifier records Wikipedia sources by the plain-text API address it fetched; fold both to the article.
const article=(u:string)=>{const x=new URL(u),t=x.pathname==='/w/api.php'?x.searchParams.get('titles'):null;return t?`${x.host}/wiki/${t.replace(/ /g,'_')}`:decodeURIComponent(x.host+x.pathname)}
const sameSource=(a:string,b:string)=>a===b||article(a)===article(b)
const witnesses=new Map<string,Witness>()
let confirmed=0,unchecked=0,rejected=0
for(const region of regions){
  const survey=read(`seed/wiki/${region}.json`) as {pages:{slug:string;sources:Source[]}[]}
  const verify=read(`seed/wiki/${region}.verify.json`) as {sources:{page:string;url:string;ok:number;bad:string[];error:string|null}[]}
  for(const page of survey.pages)for(const s of page.sources){
    const check=verify.sources.find(v=>v.page===page.slug&&sameSource(v.url,s.url))
    for(const q of s.quotes){
      if(!check||check.error){unchecked++;continue}
      if(check.bad.includes(q.text)){rejected++;continue}
      const key='url:'+s.url
      const w=witnesses.get(key)??{key,kind:'document',title:s.title,url:s.url,publisher:s.publisher??new URL(s.url).hostname,licence:s.licence??(/wikipedia\.org/.test(s.url)?'CC BY-SA 4.0':null),year:/wikipedia/.test(s.url)?null:(s.year??null),language:s.language??null,voice:voiceOf(s.url),excerpts:[]}
      const d=digest(key,q.text)
      if(!w.excerpts.some(e=>e.digest===d)){w.excerpts.push({digest:d,text:q.text,section:q.section});confirmed++}
      witnesses.set(key,w)
    }
  }
}
const catalogueWitness:Witness={key:'catalogue:tanah-papua',kind:'document',title:`Katalog konteks ${catalogue.name} ${catalogue.version}`,url:'https://github.com/yohn-maistre/strata/blob/main/src/catalogues/tanah-papua.json',publisher:'Strata, dari BIG Satu Peta dan RPJMN 2020–2024 (Bappenas)',licence:null,year:2026,language:'id',voice:'pemerintah',excerpts:[]}

// ---------- entities ----------
type Entity={slug:string;class:string;title:string;description:string;aliases:string[];context:string|null;origin:string;names:{text:string;cased:boolean}[]}
const entities=new Map<string,Entity>()
const bySlugContext=new Map<string,string>()
const englishProvince:Record<string,string>={'papua-tengah':'Central Papua','papua-pegunungan':'Highland Papua','papua-selatan':'South Papua','papua-barat':'West Papua','papua-barat-daya':'Southwest Papua'}
const plainAliases=(e:Entry)=>e.aliases.filter(a=>!/^(kabar|glottocode):/.test(a))
for(const e of catalogue.entries){
  if(e.kind==='topic')continue
  const names:{text:string;cased:boolean}[]=[]
  if(e.kind==='place'&&e.facet==='regency')names.push({text:'Kabupaten '+e.title,cased:false},{text:e.title+' Regency',cased:false},{text:e.title,cased:true})
  else if(e.kind==='place')names.push({text:e.title,cased:true})
  else if(e.facet==='province'){names.push({text:'Provinsi '+e.title,cased:false},{text:e.title+' Province',cased:false});if(e.title!=='Papua')names.push({text:e.title,cased:true});if(englishProvince[e.slug])names.push({text:englishProvince[e.slug]!,cased:true})}
  else if(e.kind==='region')names.push({text:'wilayah adat '+e.title,cased:false},{text:e.title,cased:true})
  else if(e.kind==='language')names.push({text:'bahasa '+e.title,cased:false},{text:e.title+' language',cased:false},{text:e.title+' languages',cased:false},{text:e.title,cased:true})
  for(const a of plainAliases(e))names.push({text:a,cased:true})
  const cls=e.kind==='language'?'bahasa':'tempat'
  const slug=(cls==='bahasa'?'bahasa-':'')+slugify(e.kind==='place'&&e.facet==='regency'?'kabupaten '+e.title:e.facet==='province'?'provinsi '+e.title:e.title)
  entities.set(slug,{slug,class:cls,title:e.facet==='regency'?'Kabupaten '+e.title:e.facet==='province'?'Provinsi '+e.title:e.kind==='region'?'Wilayah adat '+e.title:e.kind==='language'?'Bahasa '+e.title:e.title,description:e.description,aliases:plainAliases(e),context:e.slug,origin:'catalogue',names})
  bySlugContext.set(e.slug,slug)
}
// Seed pages: a page that is a catalogue context becomes the same entity; others become new entities.
for(const region of regions){
  const pages=read(`seed/wiki/pages/${region}.json`) as {slug:string;title:string;kind:string;text:string}[]
  for(const p of pages){
    const label=labels.pages.find(l=>l.title===p.title)
    const own=label?.contexts.map(c=>catalogue.entries.find(e=>e.slug===c)).find(e=>e&&((p.kind==='regency'&&e.facet==='regency')||(p.kind==='region'&&e.kind==='region'&&e.facet==='customary-region')||(p.kind==='language'&&e.kind==='language')))
    const lead=p.text.replace(/^#+ .*$/gm,'').replace(/\[[\d,\s]+\]/g,'').replace(/\s+/g,' ').trim().split(/(?<=\.)\s/)[0]??''
    if(own){
      const ent=entities.get(bySlugContext.get(own.slug)!)!
      ent.origin='catalogue+page'
      if(p.kind==='language'){const base=p.title.replace(/^Bahasa\s+/,'');if(!ent.title.endsWith(base)){ent.aliases.push(base);ent.names.push({text:'bahasa '+base,cased:false},{text:base+' language',cased:false})}}
      continue
    }
    const base=p.title.replace(/^(Suku|Bahasa-bahasa|Rumpun bahasa|Bahasa|Wilayah adat)\s+/,'')
    const cls=p.kind==='people'?'kelompok':p.kind==='language'?'bahasa':'tempat'
    const names:{text:string;cased:boolean}[]=[{text:p.title,cased:false}]
    if(cls==='kelompok')names.push({text:'suku '+base,cased:false},{text:'orang '+base,cased:false},{text:'masyarakat '+base,cased:false},{text:base+' people',cased:false},{text:base+' tribe',cased:false})
    if(cls==='bahasa')names.push({text:base+' languages',cased:false},{text:'bahasa '+base,cased:false})
    if(cls==='tempat'){
      const [kind,...rest]=p.title.split(' '),name=rest.join(' '),en:Record<string,string>={Danau:'Lake',Gunung:'Mount',Lembah:'Valley',Teluk:'Bay',Pulau:'Island'}
      if(en[kind!])names.push({text:kind==='Lembah'||kind==='Teluk'||kind==='Pulau'?name+' '+en[kind!]:en[kind!]+' '+name,cased:false})
      if(['Pulau','Lembah'].includes(kind!))names.push({text:name,cased:true})
    }
    const slug=slugify(p.title)
    if(!entities.has(slug))entities.set(slug,{slug,class:cls,title:p.title,description:lead.slice(0,300),aliases:[],context:null,origin:'page',names})
  }
}

// ---------- mentions ----------
type Surface={text:string;cased:boolean;entity:string}
const surfaces:Surface[]=[]
for(const e of entities.values())for(const n of e.names)if(n.text.length>=3)surfaces.push({...n,entity:e.slug})
const ambiguous=new Set<string>()
const key=(s:Surface)=>s.cased?s.text:s.text.toLowerCase()
const owners=new Map<string,Set<string>>()
for(const s of surfaces){const k=key(s);owners.set(k,(owners.get(k)??new Set()).add(s.entity))}
for(const [k,o] of owners)if(o.size>1)ambiguous.add(k)
surfaces.sort((a,b)=>b.text.length-a.text.length||a.text.localeCompare(b.text))
const boundary=(t:string,i:number)=>i<0||i>=t.length||!/[\p{L}\p{N}]/u.test(t[i]!)
type Hit={entity:string;start:number;end:number;surface:string}
function mentions(text:string):Hit[]{
  const taken=new Array(text.length).fill(false),hits:Hit[]=[]
  for(const s of surfaces){
    const hay=s.cased?text:text.toLowerCase(),needle=s.cased?s.text:s.text.toLowerCase()
    let i=hay.indexOf(needle)
    while(i>=0){
      const j=i+needle.length
      if(boundary(text,i-1)&&boundary(text,j)&&!taken.slice(i,j).some(Boolean)){
        for(let x=i;x<j;x++)taken[x]=true
        if(!ambiguous.has(key(s)))hits.push({entity:s.entity,start:i,end:j,surface:text.slice(i,j)})
      }
      i=hay.indexOf(needle,i+1)
    }
  }
  return hits.sort((a,b)=>a.start-b.start)
}

// ---------- assertions ----------
type Assertion={subject:string;predicate:string;object:string;status:'accepted'|'proposed';origin:string;support:{witness:string;excerpt:string}[]}
const assertions=new Map<string,Assertion>()
const addAssertion=(a:Omit<Assertion,'support'>,support:{witness:string;excerpt:string})=>{
  const k=a.subject+'|'+a.predicate+'|'+a.object
  const prior=assertions.get(k)
  if(prior){if(!prior.support.some(s=>s.excerpt===support.excerpt))prior.support.push(support);if(a.status==='accepted')prior.status='accepted';return}
  assertions.set(k,{...a,support:[support]})
}
// (1) Catalogue membership. The excerpt is the entry's own description, which names the parents.
for(const e of catalogue.entries){
  const subject=bySlugContext.get(e.slug)
  if(!subject||!e.parents.length)continue
  const d=digest(catalogueWitness.key,e.slug,e.description)
  if(!catalogueWitness.excerpts.some(x=>x.digest===d))catalogueWitness.excerpts.push({digest:d,text:`${e.title}: ${e.description}`,section:'catalogue'})
  for(const parent of e.parents){const object=bySlugContext.get(parent);if(object)addAssertion({subject,predicate:'bagian-dari',object,status:'accepted',origin:'catalogue'},{witness:catalogueWitness.key,excerpt:d})}
}
// (2) Cue phrases between two adjacent mentions in one confirmed quote.
type Cue={name:string;from:string[];to:string[];re:RegExp;predicate:string;reverse?:boolean}
const cues:Cue[]=[
  {name:'dihuni-oleh',from:['tempat'],to:['kelompok'],re:/\b(dihuni oleh|didiami oleh|inhabited by|home to)\b/i,predicate:'mendiami',reverse:true},
  {name:'mendiami',from:['kelompok'],to:['tempat'],re:/\b(mendiami|mendiam|tinggal di|berdiam di|menetap di|bermukim di|native to|inhabit|inhabits|live in|lives in|living in)\b/i,predicate:'mendiami'},
  {name:'dituturkan',from:['bahasa'],to:['tempat'],re:/\b(dituturkan|digunakan|dipakai|spoken|used)\b/i,predicate:'dituturkan-di'},
  {name:'dituturkan-oleh',from:['bahasa'],to:['kelompok'],re:/\b(dituturkan oleh|digunakan oleh|spoken by|used by)\b/i,predicate:'dituturkan-oleh'},
  {name:'bagian-dari',from:['tempat'],to:['tempat'],re:/\b(bagian dari|termasuk( dalam| wilayah)?|merupakan (sebuah )?(kabupaten|distrik|pulau) (yang berada )?di|is a regency (in|of)|is part of|part of)\b/i,predicate:'bagian-dari'},
  {name:'terletak-di',from:['tempat'],to:['tempat'],re:/\b(terletak di|berada di|located in|located on|lies in|situated in)\b/i,predicate:'berada-di'},
]
let proposals=0
for(const w of witnesses.values())for(const ex of w.excerpts){
  const hits=mentions(ex.text)
  ;(ex as {mentions?:Hit[]}).mentions=hits
  for(let i=0;i+1<hits.length;i++){
    const a=hits[i]!,b=hits[i+1]!,between=ex.text.slice(a.end,b.start)
    if(a.entity===b.entity||between.length>80||/[.;:!?]/.test(between))continue
    const ea=entities.get(a.entity)!,eb=entities.get(b.entity)!
    for(const cue of cues){
      if(!cue.from.includes(ea.class)||!cue.to.includes(eb.class))continue
      const m=cue.re.exec(between)
      // The cue must lead straight to the second name: a coordinated clause ("... dan dihuni oleh") has
      // another subject, and a relative clause after the cue ("terletak di wilayah ... di mana") another object.
      if(!m||/^\s*(dan|and|serta|,)\b/i.test(between))continue
      const rest=between.slice(m.index+m[0].length)
      if(rest.length>30||/\b(di mana|where|which|yang|that)\b/i.test(rest))continue
      const [subject,object]=cue.reverse?[b.entity,a.entity]:[a.entity,b.entity]
      addAssertion({subject,predicate:cue.predicate,object,status:'proposed',origin:'cue:'+cue.name},{witness:w.key,excerpt:ex.digest})
      proposals++
      break
    }
  }
}

// ---------- output ----------
const mentioned=new Set<string>(),mentionRows:{entity:string;witness:string;excerpt:string;surface:string}[]=[]
for(const w of witnesses.values())for(const ex of w.excerpts)for(const h of (ex as {mentions?:Hit[]}).mentions??[]){
  if(!mentionRows.some(m=>m.entity===h.entity&&m.excerpt===ex.digest))mentionRows.push({entity:h.entity,witness:w.key,excerpt:ex.digest,surface:h.surface});mentioned.add(h.entity)
}
for(const a of assertions.values()){mentioned.add(a.subject);mentioned.add(a.object)}
// Keep catalogue languages only if something mentions them; keep every place, region and page entity.
const keep=[...entities.values()].filter(e=>e.class!=='bahasa'||e.origin!=='catalogue'||mentioned.has(e.slug))
const keepSet=new Set(keep.map(e=>e.slug))
const out={
  version:1,
  about:'First slice of the knowledge model, built by scripts/build-knowledge-seed.ts from the verified seed quotes and the catalogue. Membership from the catalogue is accepted; cue-phrase statements are proposals for review. No language model was used.',
  entities:keep.map(({names:_n,...e})=>e),
  witnesses:[...witnesses.values(),catalogueWitness].map(w=>({...w,excerpts:w.excerpts.map(({digest,text,section})=>({digest,text,section}))})),
  mentions:mentionRows.filter(m=>keepSet.has(m.entity)),
  assertions:[...assertions.values()].filter(a=>keepSet.has(a.subject)&&keepSet.has(a.object)),
  stats:{confirmedQuotes:confirmed,uncheckedQuotes:unchecked,rejectedQuotes:rejected,entities:keep.length,mentions:mentionRows.length,ambiguousNames:ambiguous.size,acceptedAssertions:[...assertions.values()].filter(a=>a.status==='accepted').length,proposedAssertions:[...assertions.values()].filter(a=>a.status==='proposed').length,cueMatches:proposals},
}
const target=process.argv[2]??root+'src/catalogues/tanah-papua-knowledge-seed.json'
writeFileSync(target,JSON.stringify(out)+'\n')
console.log(JSON.stringify(out.stats))
